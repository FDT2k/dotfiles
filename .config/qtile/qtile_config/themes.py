# themes.py - Color scheme integration (hellwal, pywal-compatible colors.json) and theme classes

import json
import os
import re

from libqtile.log_utils import logger

home = os.path.expanduser('~')
COLORS_JSON = home + '/.cache/wal/colors.json'

# Fallback when colors.json is missing or unusable (fresh machine, hellwal not
# run yet, broken template): Qtile must still start, with a neutral dark palette.
DEFAULT_COLORS = [
    '#1d1f21', '#cc6666', '#b5bd68', '#f0c674',
    '#81a2be', '#b294bb', '#8abeb7', '#c5c8c6',
    '#666666', '#d54e53', '#b9ca4a', '#e7c547',
    '#7aa6da', '#c397d8', '#70c0b1', '#eaeaea',
]


def load_colors():
    """Return (wallpaper, alpha, colors) from colors.json, or the fallback."""
    try:
        with open(COLORS_JSON) as wal_import:
            data = json.load(wal_import)
        values = list(data['colors'].values())
        if len(values) < 16 or not all(
                isinstance(v, str) and re.fullmatch(r'#[0-9a-fA-F]{6}', v)
                for v in values[:16]):
            raise ValueError('colors must hold 16 #rrggbb values')
        return data.get('wallpaper', ''), data.get('alpha', '100'), values
    except Exception as e:
        logger.warning('theme: %s unusable (%s), using default palette '
                       '— run bin/theme/hellwal-apply <image>', COLORS_JSON, e)
        return '', '100', list(DEFAULT_COLORS)


# Color scheme import: ~/.cache/wal/colors.json is generated by hellwal from
# ~/.config/hellwal/templates/colors.json (same format as pywal's)
# from https://github.com/gibranlp/QARSlp/blob/6da11eb970a8b2560912eddef1615ebbbc19a048/dotfiles/.config/qtile/funct.py#L26
wallpaper, alpha, val_colors = load_colors()


def init_colors():
    return [*val_colors]


color = init_colors()


class theme:
    bg = color[0]
    fg = color[7]
    bg_active = color[1]
    contrasted = color[6]
    bg_other = color[8]
    margin = 10


class theme_neg:
    bg = color[2]
    fg = color[0]
    bg_active = color[6]
    contrasted = color[7]
    bg_other = color[6]
    margin = 10
